using ReLearn.Infrastructure;
using ReLearn.Model;
using ReLearn.Output;

namespace ReLearn.Generators;

/// Emits BMAD-Method brownfield project knowledge (the same document set BMAD's `document-project`
/// workflow produces, enriched with rules/flows/journeys) plus planning seeds for the Analyst, PM and
/// Architect agents: modernization-brief.md → PRD, target-architecture-guidance.md → architecture,
/// epics-seed.md → epics & stories, project-context.md → dev agents.
public sealed class BmadGenerator
{
    private readonly PackView _v;
    private readonly string _docs;
    private readonly string _date = DateTime.UtcNow.ToString("yyyy-MM-dd");
    private KnowledgePack P => _v.Pack;

    public BmadGenerator(PackView v, string docsDir) { _v = v; _docs = docsDir; }

    public List<string> Run()
    {
        var files = new List<string>();
        void Save(string name, string content) { Md.Save(Path.Combine(_docs, name), content); files.Add(Path.Combine(_docs, name)); }
        Save("project-overview.md", Overview());
        Save("architecture-legacy.md", Architecture());
        Save("source-tree-analysis.md", SourceTree());
        Save("component-inventory.md", Components());
        Save("data-models.md", DataModels());
        Save("api-contracts.md", Api());
        Save("integration-architecture.md", Integrations());
        Save("business-rules.md", Rules());
        Save("business-flows.md", Flows());
        Save("user-journeys.md", Journeys());
        Save("modernization-brief.md", Brief());
        Save("target-architecture-guidance.md", TargetGuidance());
        Save("epics-seed.md", Epics());
        Save("project-context.md", ProjectContext());
        Save("index.md", Index());
        return files;
    }

    private string Header(string title, string purpose) =>
        new Md().L($"# {title}").Nl().L($"> Generated by ReLearn {_date} from `{P.Manifest.Input}` · {purpose}").Nl().ToString();

    private string Index()
    {
        var md = new Md().L(Header("Project Documentation Index", "entry point for BMAD agents (project_knowledge)"));
        md.H(2, "Legacy system (as-is)");
        foreach (var (f, d) in new[]
        {
            ("project-overview.md", "what the system is, size, technology"), ("architecture-legacy.md", "projects, layers, dependencies"),
            ("source-tree-analysis.md", "where things live"), ("component-inventory.md", "classes by stereotype"),
            ("data-models.md", "entities, tables, procedures, SQL"), ("api-contracts.md", "endpoints, screens, message handlers"),
            ("integration-architecture.md", "cache, queues, Kafka, HTTP, files, platform APIs"), ("business-rules.md", "extracted rule catalogue"),
            ("business-flows.md", "end-to-end flows with sequence diagrams"), ("user-journeys.md", "screen navigation and journeys"),
        }) md.Bullet($"[{f}](./{f}) — {d}");
        md.H(2, "Modernization (to-be) seeds");
        md.Bullet("[modernization-brief.md](./modernization-brief.md) — input for the Analyst / PM (`create-prd`)");
        md.Bullet("[target-architecture-guidance.md](./target-architecture-guidance.md) — input for the Architect (`create-architecture`)");
        md.Bullet("[epics-seed.md](./epics-seed.md) — input for `create-epics-and-stories`");
        md.Bullet("[project-context.md](./project-context.md) — rules every dev agent must follow");
        md.H(2, "Machine-readable source");
        md.P("The full knowledge pack (JSON) lives next to the repository; capability bundles in `capabilities/<slug>.json` are sized to load one at a time.");
        return md.ToString();
    }

    private string Overview()
    {
        var md = new Md().L(Header("Project Overview", "brownfield document-project equivalent"));
        md.Table(new[] { "metric", "value" }, P.Manifest.Counts.Select(kv => new[] { kv.Key, kv.Value.ToString() }));
        md.H(2, "Projects");
        md.Table(new[] { "project", "kind", "frameworks", "LOC", "key packages" },
            P.Dependencies.Projects.Select(p => new[] { p.Name, p.Kind, string.Join(", ", p.TargetFrameworks), p.LinesOfCode.ToString(), string.Join(", ", p.Packages.Select(x => x.Name).Take(8)) }));
        md.H(2, "Capabilities");
        md.Table(new[] { "id", "capability", "priority", "flows", "rules", "entities" },
            P.Capabilities.Select(c => new[] { c.Id, c.Name, c.Priority, c.Flows.Count.ToString(), c.Rules.Count.ToString(), string.Join(", ", c.Entities.Take(5)) }));
        return md.ToString();
    }

    private string Architecture()
    {
        var md = new Md().L(Header("Legacy Architecture", "as-is structure for the Architect"));
        md.H(2, "Project dependencies"); md.Code("mermaid", Mermaid.Projects(P.Dependencies));
        md.H(2, "Layering (observed calls between stereotypes)"); md.Code("mermaid", Mermaid.Layers(P.Dependencies));
        md.H(2, "Dependency injection");
        md.Table(new[] { "service", "implementation", "lifetime", "container" }, P.Dependencies.DiRegistrations.Take(200).Select(d => new[] { d.Service, d.Implementation ?? "", d.Lifetime, d.Container }));
        md.H(2, "Most coupled namespaces");
        md.Table(new[] { "from", "to", "weight" }, P.Dependencies.NamespaceEdges.Take(40).Select(e => new[] { e.From, e.To, e.Weight.ToString() }));
        md.H(2, "External API usage by project");
        md.Table(new[] { "project", "namespace", "calls" }, P.Dependencies.ExternalNamespaceUsage.Where(e => !e.To.StartsWith("System.Linq") && !e.To.StartsWith("System.Collections")).Take(80).Select(e => new[] { e.From, e.To, e.Weight.ToString() }));
        md.H(2, "Hotspots (cyclomatic complexity ≥ 10)");
        md.Table(new[] { "method", "complexity", "LOC", "source" }, P.CallGraph.Nodes.Where(n => n.CyclomaticComplexity >= 10).OrderByDescending(n => n.CyclomaticComplexity).Take(40)
            .Select(n => new[] { _v.MethodName(n.Id), n.CyclomaticComplexity.ToString(), n.LinesOfCode.ToString(), _v.Evidence(n.Location) }));
        return md.ToString();
    }

    private string SourceTree()
    {
        var md = new Md().L(Header("Source Tree Analysis", "where to find things"));
        foreach (var g in P.Dependencies.Types.GroupBy(t => t.Project))
        {
            md.H(2, g.Key);
            var dirs = g.SelectMany(t => t.Files).Select(f => Path.GetDirectoryName(f)?.Replace('\\', '/') ?? "").GroupBy(d => d).OrderBy(d => d.Key);
            md.Table(new[] { "folder", "files", "stereotypes" }, dirs.Select(d => new[]
            {
                d.Key, d.Count().ToString(),
                string.Join(", ", g.Where(t => t.Files.Any(f => (Path.GetDirectoryName(f)?.Replace('\\', '/') ?? "") == d.Key)).GroupBy(t => t.Stereotype).Select(s => $"{s.Key}×{s.Count()}")),
            }));
        }
        return md.ToString();
    }

    private string Components()
    {
        var md = new Md().L(Header("Component Inventory", "types grouped by stereotype"));
        foreach (var g in P.Dependencies.Types.Where(t => t.Stereotype != "test").GroupBy(t => t.Stereotype).OrderBy(g => g.Key))
        {
            md.H(2, $"{g.Key} ({g.Count()})");
            md.Table(new[] { "type", "namespace", "base / interfaces", "source" }, g.Take(150).Select(t => new[] { t.Name, t.Namespace, string.Join(", ", new[] { t.BaseType }.Concat(t.Interfaces).Where(x => x != null)), _v.Evidence(t.Location) }));
        }
        return md.ToString();
    }

    private string DataModels()
    {
        var md = new Md().L(Header("Data Models", "entities, database objects, data access"));
        md.Code("mermaid", Mermaid.Er(P.Data.Entities));
        md.H(2, "Contexts");
        md.Table(new[] { "context", "technology", "entity sets" }, P.Data.Contexts.Select(c => new[] { c.Name, c.Technology, string.Join(", ", c.EntitySets) }));
        md.H(2, "Entities");
        foreach (var e in P.Data.Entities)
        {
            md.H(3, $"{e.Name} → `{e.Table ?? e.Name}`");
            md.Table(new[] { "field", "type", "key", "constraints", "relation" }, e.Properties.Select(p => new[] { p.Name, p.Type, p.IsKey ? "PK" : "", string.Join(", ", p.Constraints), p.NavigationTo ?? "" }));
        }
        md.H(2, "Database objects");
        md.Table(new[] { "object", "kind", "source", "columns / deps", "used by" }, P.Data.DbObjects.Select(o => new[] { o.Name, o.Kind, o.Source, string.Join(", ", o.Columns.Take(10)), string.Join(", ", o.ReferencedBy.Take(3).Select(_v.MethodName)) }));
        md.H(2, "Connections (redacted)");
        md.Table(new[] { "name", "provider", "file" }, P.Data.Connections.Select(c => new[] { c.Name, c.Provider, c.File }));
        md.H(2, "Data operations");
        md.Table(new[] { "method", "op", "targets", "tech", "sql" }, P.Data.Operations.Take(400).Select(o => new[] { _v.MethodName(o.MethodId), o.Operation, string.Join(", ", o.Targets), o.Technology, o.Sql == null ? "" : "`" + Text.OneLine(o.Sql, 140) + "`" }));
        return md.ToString();
    }

    private string Api()
    {
        var md = new Md().L(Header("API & Entry-Point Contracts", "everything that starts a flow"));
        foreach (var g in P.EntryPoints.GroupBy(e => e.Kind))
        {
            md.H(2, g.Key);
            md.Table(new[] { "id", "name", "route / trigger", "params", "auth", "source" }, g.Select(e => new[]
            {
                e.Id, e.Name, e.Route ?? e.Trigger ?? "", string.Join("; ", e.Parameters),
                e.AllowAnonymous ? "anonymous" : string.Join(", ", e.Roles.Concat(e.Policies).DefaultIfEmpty(e.RequiresAuth ? "authenticated" : "")), _v.Evidence(e.Location),
            }));
        }
        return md.ToString();
    }

    private string Integrations()
    {
        var md = new Md().L(Header("Integration Architecture", "caches, queues, streams, external services, platform APIs"));
        foreach (var g in P.Integrations.Points.Where(i => i.Category != "config").GroupBy(i => i.Category).OrderBy(g => g.Key))
        {
            md.H(2, g.Key);
            md.Table(new[] { "id", "technology", "direction", "operation", "target", "in method", "source" },
                g.Select(i => new[] { i.Id, i.Technology, i.Direction, i.Operation, i.Target ?? "", _v.MethodName(i.MethodId), _v.Evidence(i.Location) }));
        }
        md.H(2, "Configuration keys read in code");
        md.Table(new[] { "key", "in method" }, P.Integrations.Points.Where(i => i.Category == "config" && i.Target != null).GroupBy(i => i.Target!).Select(g => new[] { g.Key, string.Join(", ", g.Select(i => _v.MethodName(i.MethodId)).Distinct().Take(3)) }));
        md.H(2, "Service endpoints (config / contracts)");
        foreach (var e in P.Integrations.ServiceEndpoints.Distinct()) md.Bullet(e);
        return md.ToString();
    }

    private string Rules()
    {
        var md = new Md().L(Header("Business Rules Catalogue", "candidates extracted from code; confirm with domain experts"));
        foreach (var g in P.Rules.GroupBy(r => r.Kind).OrderBy(g => g.Key))
        {
            md.H(2, $"{g.Key} ({g.Count()})");
            md.Table(new[] { "id", "rule", "condition / expression", "outcome", "conf.", "source" }, g.Select(r => new[]
            {
                r.Id, Text.OneLine(r.Title, 120), "`" + Text.OneLine(r.Condition ?? r.Expression, 160) + "`",
                Text.OneLine(r.Outcome ?? (r.Table != null ? string.Join("; ", r.Table.Select(x => $"{x[0]}→{x[1]}")) : ""), 160), r.Confidence, _v.Evidence(r.Location),
            }));
        }
        return md.ToString();
    }

    private string Flows()
    {
        var md = new Md().L(Header("Business Flows", "entry point → call graph → data & integrations"));
        foreach (var c in P.Capabilities)
        {
            md.H(2, $"{c.Name} ({c.Id}, {c.Priority})");
            foreach (var fid in c.Flows.Where(_v.Flows.ContainsKey))
            {
                var f = _v.Flows[fid];
                md.H(3, $"{f.Id}: {f.Name}");
                md.P($"Trigger `{f.Trigger}` · actor {PackView.Actor(f)} · layers {string.Join(" → ", f.Layers)} · rules {string.Join(", ", f.Rules)}");
                md.Code("mermaid", Mermaid.Sequence(f, 20));
            }
        }
        return md.ToString();
    }

    private string Journeys()
    {
        var md = new Md().L(Header("User Journeys", "derived from navigation, screens and entry points"));
        md.H(2, "Screens");
        md.Table(new[] { "id", "name", "kind", "fields", "actions" }, P.Journeys.Screens.Select(s => new[] { s.Id, s.Name, s.Kind, string.Join(", ", s.Fields.Take(10)), string.Join(", ", s.Actions.Take(10)) }));
        foreach (var j in P.Journeys.Journeys)
        {
            md.H(2, $"{j.Id}: {j.Name}");
            md.P($"Channel {j.Channel} · actor {j.Actor} · derived from {j.Derivation} · confidence {j.Confidence}");
            md.Code("mermaid", Mermaid.Journey(j, P.Journeys));
            md.Table(new[] { "#", "screen", "action", "flows" }, j.Steps.Select(s => new[] { s.Order.ToString(), s.Screen, s.Action ?? "", string.Join(", ", s.Flows) }));
        }
        return md.ToString();
    }

    private string Brief()
    {
        var t = _v.Target;
        var md = new Md().L(Header("Modernization Product Brief", "input for BMAD Analyst/PM → PRD"));
        md.H(2, "Problem statement");
        md.P($"Re-platform the legacy .NET system ({string.Join(", ", P.Dependencies.Projects.Where(p => !p.IsTest).Select(p => $"{p.Name} [{p.Kind}]"))}) onto **{t.Name}** without losing business behaviour. The system exposes {P.EntryPoints.Count} entry points across {P.Capabilities.Count} capabilities, enforces {P.Rules.Count(r => !r.Trivial)} extracted business rules and depends on {P.Integrations.Points.Where(i => i.Category != "config").Select(i => i.Technology).Distinct().Count()} integration technologies.");
        md.H(2, "Goals");
        md.Bullet("Functional parity for every capability listed below, proven by characterization tests.");
        md.Bullet($"Adopt the target stack: {string.Join("; ", t.Stack.Select(kv => $"{kv.Key}: {kv.Value}"))}.");
        md.Bullet("Incremental cut-over per capability (strangler fig) with rollback.");
        md.Bullet("[NEEDS CLARIFICATION: business goals beyond parity — UX redesign, new features, cost targets]");
        md.H(2, "Users / actors");
        foreach (var a in P.Flows.SelectMany(f => f.Roles).Where(r => !r.StartsWith("policy:")).Distinct().DefaultIfEmpty("user (no role-based authorization found)")) md.Bullet(a);
        md.H(2, "Scope — capabilities (MVP = P1)");
        md.Table(new[] { "id", "capability", "priority", "flows", "rules", "integrations" }, P.Capabilities.Select(c => new[] { c.Id, c.Name, c.Priority, c.Flows.Count.ToString(), c.Rules.Count.ToString(), string.Join(", ", c.Integrations.Where(_v.Integrations.ContainsKey).Select(i => _v.Integrations[i].Technology).Distinct()) }));
        md.H(2, "Constraints & risks");
        foreach (var r in Risks()) md.Bullet(r);
        md.H(2, "Out of scope (proposed)");
        md.Bullet("Functional changes not required for parity, unless captured as new requirements in the PRD.");
        return md.ToString();
    }

    private IEnumerable<string> Risks()
    {
        var platform = P.Integrations.Points.Where(i => i.Category == "platform").Select(i => i.Technology).Distinct().ToList();
        if (platform.Count > 0) yield return $"Windows/platform-specific dependencies: {string.Join(", ", platform)} — need portable replacements on {_v.Target.Name}.";
        var procs = P.Data.DbObjects.Count(o => o.Kind is "procedure" or "function" or "trigger");
        if (procs > 0) yield return $"{procs} stored procedures/functions/triggers — decide: keep in DB, or port logic to the application layer.";
        var dyn = P.Data.Operations.Count(o => o.DynamicSql);
        if (dyn > 0) yield return $"{dyn} dynamic SQL sites — reproduce query semantics; eliminate injection risk.";
        if (P.Manifest.SemanticFidelity != "full") yield return "Static analysis ran in ad-hoc mode — some calls through third-party libraries are unresolved.";
        var lowRules = P.Rules.Count(r => r.Confidence == "low");
        if (lowRules > 0) yield return $"{lowRules} low-confidence rule candidates need expert review.";
        yield return "Behaviour driven by configuration or data (reference tables, feature flags) is not visible to static analysis.";
    }

    private string TargetGuidance()
    {
        var t = _v.Target;
        var md = new Md().L(Header($"Target Architecture Guidance — {t.Name}", "input for BMAD Architect → architecture.md"));
        md.P(t.Summary);
        md.H(2, "Stack"); md.Table(new[] { "concern", "choice" }, t.Stack.Select(kv => new[] { kv.Key, kv.Value }));
        md.H(2, "Layout"); md.Code("text", string.Join("\n", t.ProjectLayout));
        md.H(2, "Legacy → target mappings for constructs present in this system");
        md.Table(new[] { "legacy", "target", "rationale", "alternatives" }, _v.MappingsFor().Select(m => new[] { m.Legacy, m.Target, m.Rationale ?? "", m.Alternatives ?? "" }));
        md.H(2, "Conventions"); foreach (var c in t.Conventions) md.Bullet(c);
        md.H(2, "Testing"); foreach (var c in t.Testing) md.Bullet(c);
        md.H(2, "Non-functional"); foreach (var c in t.NonFunctional) md.Bullet(c);
        md.H(2, "Suggested bounded contexts / modules");
        md.P("One module per capability (adjust after domain review):");
        foreach (var c in P.Capabilities) md.Bullet($"`{c.Slug}` — entities {string.Join(", ", c.Entities.Take(6).DefaultIfEmpty("—"))}; integrations {string.Join(", ", c.Integrations.Where(_v.Integrations.ContainsKey).Select(i => _v.Integrations[i].Technology).Distinct().DefaultIfEmpty("—"))}");
        return md.ToString();
    }

    private string Epics()
    {
        var md = new Md().L(Header("Epics & Stories Seed", "input for BMAD PM `create-epics-and-stories`"));
        md.P("One epic per capability, one story per legacy flow. Acceptance criteria reference rule ids so the Dev and QA agents can trace to `business-rules.md`.");
        var e = 0;
        foreach (var c in P.Capabilities)
        {
            e++;
            md.H(2, $"Epic {e}: Modernize {c.Name} ({c.Id}, {c.Priority})");
            md.P($"Goal: deliver {c.Name} on {_v.Target.Name} with parity for {c.Flows.Count} flow(s) and {c.Rules.Count} rule(s).");
            if (c.Description != null) md.P(c.Description);
            var s = 0;
            md.H(3, $"Story {e}.{++s}: Characterization tests for {c.Name}");
            md.P("As a developer, I want recorded legacy inputs/outputs for every flow in this capability, so that parity can be proven automatically.");
            md.L("Acceptance criteria:").Bullet(string.Join(", ", c.Flows) + " each have ≥1 golden test case recorded against legacy").Nl();
            foreach (var fid in c.Flows.Where(_v.Flows.ContainsKey))
            {
                var f = _v.Flows[fid];
                md.H(3, $"Story {e}.{++s}: {f.BusinessName ?? f.Name}");
                md.P($"As a {PackView.Actor(f)}, I want `{f.BusinessName ?? f.Name}` on the new platform, so that {f.Goal ?? "I keep doing my work without change"}.");
                md.L("Acceptance criteria:");
                md.Bullet($"Characterization tests for {f.Id} pass.");
                foreach (var rid in f.Rules.Where(_v.Rules.ContainsKey).Take(15)) { var r = _v.Rules[rid]; md.Bullet($"{r.Id} ({r.Kind}): {Text.OneLine(r.BusinessStatement ?? r.Title, 140)}"); }
                foreach (var (ent, ops) in f.EntityOperations) md.Bullet($"Persists `{ent}` ({string.Join("/", ops)}) compatibly.");
                foreach (var i in f.Integrations.Take(6)) md.Bullet($"Integration {i}");
                md.Nl();
            }
            if (c.Entities.Count > 0)
            {
                md.H(3, $"Story {e}.{++s}: Migrate data for {c.Name}");
                md.P($"Migrate {string.Join(", ", c.Entities)} with reconciliation (counts + checksums) and rollback.");
            }
        }
        return md.ToString();
    }

    private string ProjectContext()
    {
        var t = _v.Target;
        var md = new Md().L("# Project Context for AI Agents").Nl()
            .P($"_Critical rules for any agent implementing the modernization of `{Path.GetFileName(P.Manifest.Input)}` onto **{t.Name}**._");
        md.H(2, "Technology stack"); foreach (var (k, v) in t.Stack) md.Bullet($"{k}: {v}");
        md.H(2, "Critical implementation rules");
        md.Bullet("Behavioural parity first: every story cites legacy ids (BR-, FLOW-, EP-, INT-). Do not \"improve\" a rule without a PRD change.");
        md.Bullet("Before coding a flow, read its capability bundle (`capabilities/<slug>.json`) and the rule details in `business-rules.md`.");
        md.Bullet("Preserve numeric semantics: legacy `decimal` math and rounding must be reproduced exactly (see calculation rules).");
        md.Bullet("Preserve external contracts listed in `api-contracts.md` and `integration-architecture.md`.");
        md.Bullet("Never copy legacy secrets; connection strings in the pack are redacted.");
        foreach (var c in t.Conventions) md.Bullet(c);
        md.H(2, "Testing rules"); foreach (var c in t.Testing) md.Bullet(c);
        return md.ToString();
    }
}
