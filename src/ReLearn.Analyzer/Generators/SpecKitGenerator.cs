using System.Text.RegularExpressions;
using ReLearn.Infrastructure;
using ReLearn.Model;
using ReLearn.Output;

namespace ReLearn.Generators;

/// Emits GitHub Spec Kit artifacts: a modernization constitution, and one feature folder per capability
/// (spec.md, data-model.md, contracts/, research.md, checklists/parity.md, legacy-evidence.md) that
/// /speckit.clarify → /speckit.plan → /speckit.tasks → /speckit.implement can consume directly.
public sealed class SpecKitGenerator
{
    private readonly PackView _v;
    private readonly string _out;
    private readonly string _date = DateTime.UtcNow.ToString("yyyy-MM-dd");

    public SpecKitGenerator(PackView view, string outRoot) { _v = view; _out = outRoot; }

    public List<string> Run(IReadOnlyCollection<string>? onlyCapabilities = null)
    {
        var written = new List<string>();
        void Save(string rel, string content) { Md.Save(Path.Combine(_out, rel), content); written.Add(rel); }

        // ---------------- constitution
        var constPath = Path.Combine(_out, ".specify/memory/constitution.md");
        var constRel = File.Exists(constPath) && !File.ReadAllText(constPath).Contains("[PROJECT_NAME]")
            ? ".specify/memory/constitution.relearn.md"   // never clobber a customised constitution
            : ".specify/memory/constitution.md";
        Save(constRel, Constitution());

        // ---------------- shared relearn context for /speckit.plan
        Save(".specify/relearn/target-profile.md", TargetProfileDoc());
        Save(".specify/relearn/parity-matrix.md", ParityMatrix());
        Save(".specify/relearn/README.md", ContextReadme());

        // ---------------- features
        var specsDir = Path.Combine(_out, "specs");
        var next = 1;
        if (Directory.Exists(specsDir))
            next = Directory.GetDirectories(specsDir).Select(d => Regex.Match(Path.GetFileName(d), @"^(\d+)-").Groups[1].Value)
                .Where(s => s.Length > 0).Select(s => int.Parse(s)).DefaultIfEmpty(0).Max() + 1;

        var index = new Md().H(1, "Modernization feature index (ReLearn → Spec Kit)")
            .P($"Target: **{_v.Target.Name}**. Generated {_date}. Order follows capability priority; run `/speckit.clarify` then `/speckit.plan` inside each feature.");
        var rows = new List<string[]>();
        foreach (var cap in _v.Pack.Capabilities.OrderBy(c => c.Priority).ThenBy(c => c.Id))
        {
            if (onlyCapabilities is { Count: > 0 } && !onlyCapabilities.Contains(cap.Id) && !onlyCapabilities.Contains(cap.Slug)) continue;
            var existing = Directory.Exists(specsDir) ? Directory.GetDirectories(specsDir, $"*-{cap.Slug}").FirstOrDefault() : null;
            var folder = existing != null ? Path.GetFileName(existing) : $"{next++:000}-{cap.Slug}";
            var dir = $"specs/{folder}";
            Save($"{dir}/spec.md", Spec(cap, folder));
            Save($"{dir}/data-model.md", DataModel(cap));
            Save($"{dir}/contracts/legacy-interface.md", Contracts(cap));
            Save($"{dir}/research.md", Research(cap));
            Save($"{dir}/checklists/parity.md", Checklist(cap));
            Save($"{dir}/legacy-evidence.md", Evidence(cap));
            rows.Add(new[] { folder, cap.Name, cap.Priority, cap.Flows.Count.ToString(), cap.Rules.Count.ToString(), string.Join(", ", cap.Entities.Take(5)) });
        }
        index.Table(new[] { "feature", "capability", "priority", "flows", "rules", "entities" }, rows);
        Save(".specify/relearn/feature-index.md", index.ToString());
        return written;
    }

    // =========================================================================================
    private string Constitution()
    {
        var t = _v.Target;
        var md = new Md();
        md.L($"# {Path.GetFileName(_v.Pack.Manifest.Input)} Modernization Constitution").Nl();
        md.P($"> Generated by ReLearn from static analysis of the legacy .NET system. Ratify or amend with `/speckit.constitution`. Target platform: **{t.Name}**.");
        md.H(2, "Core Principles");
        md.H(3, "I. Behavioural Parity (NON-NEGOTIABLE)");
        md.P("Every legacy business rule (`BR-xxxx`) referenced by a feature spec MUST be implemented and covered by an automated test that asserts the legacy outcome. A rule may be dropped only with an explicit, recorded product decision in the feature's `spec.md` under *Assumptions*.");
        md.H(3, "II. Traceability");
        md.P("Each functional requirement MUST cite its legacy evidence (rule id, flow id, entry point id, or source location from the ReLearn knowledge pack). Plans and tasks MUST keep these ids so reviewers can trace new code back to legacy behaviour.");
        md.H(3, "III. Contract Compatibility");
        md.P("Externally visible contracts — HTTP routes and payloads, message topics/queues and schemas, file formats, database objects shared with other systems — MUST remain compatible unless the feature spec explicitly versions them. Consumers are identified in `contracts/legacy-interface.md`.");
        md.H(3, "IV. Data Fidelity");
        md.P("Entities, keys, constraints and reference data MUST be migrated without loss. Schema changes require a migration plan with reconciliation (row counts and checksums) and a rollback path.");
        md.H(3, "V. Characterization Tests First");
        md.P("Before re-implementing a capability, record characterization tests (golden inputs/outputs) against the legacy system for each flow in the feature. New code is done when those tests pass on the target platform.");
        md.H(3, "VI. Incremental, Strangler-Fig Delivery");
        md.P("Capabilities are migrated one feature at a time behind a routing seam (API gateway, reverse proxy, or desktop shell module) so legacy and modern implementations can run side by side and be switched per capability.");
        md.H(3, "VII. Target Platform Standards");
        foreach (var (k, v) in t.Stack) md.Bullet($"**{k}**: {v}");
        md.Nl();
        foreach (var c in t.Conventions) md.Bullet(c);
        md.Nl();
        md.H(2, "Quality Gates");
        foreach (var q in t.Testing) md.Bullet(q);
        foreach (var n in t.NonFunctional) md.Bullet(n);
        md.Bullet("Security: legacy roles and policies (see `.specify/relearn/parity-matrix.md`) MUST map 1:1 to target authorization rules.");
        md.Bullet("No secrets in code or config; legacy connection strings are redacted in the knowledge pack and must be re-provisioned via the target secret store.");
        md.Nl();
        md.H(2, "Governance");
        md.P("This constitution supersedes ad-hoc practices for the modernization program. Amendments require updating this file, the affected feature specs, and the parity matrix.");
        md.P($"**Version**: 1.0.0 | **Ratified**: {_date} | **Last Amended**: {_date}");
        return md.ToString();
    }

    private string TargetProfileDoc()
    {
        var t = _v.Target;
        var md = new Md().H(1, $"Target profile: {t.Name}").P(t.Summary);
        md.H(2, "Stack");
        md.Table(new[] { "concern", "choice" }, t.Stack.Select(kv => new[] { kv.Key, kv.Value }));
        md.H(2, "Project layout");
        md.Code("text", string.Join("\n", t.ProjectLayout));
        md.H(2, "Legacy → target mapping (only constructs found in this codebase)");
        md.Table(new[] { "legacy construct", "target", "notes" }, _v.MappingsFor().Select(m => new[] { m.Legacy, m.Target, m.Notes ?? m.Rationale ?? "" }));
        var facts = _v.Facts();
        var unmapped = facts.Where(f => f != "always" && !_v.Target.Mappings.Any(m => m.Match == f)).OrderBy(f => f).ToList();
        if (unmapped.Count > 0)
        {
            md.H(2, "Legacy constructs without a predefined mapping");
            md.P("Decide these during `/speckit.plan` (record the decision in the feature's research.md):");
            foreach (var u in unmapped) md.Bullet($"`{u}`");
        }
        return md.ToString();
    }

    private string ContextReadme() => new Md()
        .H(1, "ReLearn context for Spec Kit")
        .P("These files are generated from the ReLearn knowledge pack and are read by `/speckit.plan` and `/speckit.analyze`:")
        .Bullet("`target-profile.md` — target stack, layout and legacy→target mappings")
        .Bullet("`parity-matrix.md` — every rule/flow/integration/data object and the feature that owns it")
        .Bullet("`feature-index.md` — generated feature folders in priority order")
        .Nl()
        .P($"Knowledge pack source: `{_v.Pack.Manifest.Input}` (generated {_v.Pack.Manifest.GeneratedAtUtc}).")
        .ToString();

    private string ParityMatrix()
    {
        var md = new Md().H(1, "Legacy parity matrix");
        md.P("Tick items off as the owning feature's tests pass on the target. Items with no owning capability need a decision.");
        var owner = new Dictionary<string, string>();
        foreach (var c in _v.Pack.Capabilities)
        {
            foreach (var r in c.Rules) owner.TryAdd(r, c.Slug);
            foreach (var f in c.Flows) owner.TryAdd(f, c.Slug);
            foreach (var i in c.Integrations) owner.TryAdd(i, c.Slug);
        }
        md.H(2, "Business rules");
        md.Table(new[] { "✓", "id", "kind", "rule", "confidence", "feature", "source" },
            _v.Pack.Rules.Select(r => new[] { "☐", r.Id, r.Kind, Text.OneLine(r.Title, 120), r.Confidence, owner.GetValueOrDefault(r.Id, "**unassigned**"), _v.Evidence(r.Location) }));
        md.H(2, "Flows");
        md.Table(new[] { "✓", "id", "flow", "trigger", "mutates", "feature" },
            _v.Pack.Flows.Select(f => new[] { "☐", f.Id, f.Name, f.Trigger, f.Mutates ? "yes" : "no", owner.GetValueOrDefault(f.Id, "**unassigned**") }));
        md.H(2, "Integrations");
        md.Table(new[] { "✓", "id", "category", "technology", "operation", "target", "feature", "source" },
            _v.Pack.Integrations.Points.Where(i => i.Category != "config").Select(i => new[] { "☐", i.Id, i.Category, i.Technology, i.Operation, i.Target ?? "", owner.GetValueOrDefault(i.Id, "**unassigned**"), _v.Evidence(i.Location) }));
        md.H(2, "Database objects");
        md.Table(new[] { "✓", "object", "kind", "source", "referenced by" },
            _v.Pack.Data.DbObjects.Select(o => new[] { "☐", o.Name, o.Kind, o.Source, string.Join(", ", o.ReferencedBy.Take(4).Select(_v.MethodName)) }));
        md.H(2, "Authorization");
        md.Table(new[] { "entry point", "roles", "policies", "anonymous" },
            _v.Pack.EntryPoints.Where(e => e.Roles.Count + e.Policies.Count > 0 || e.AllowAnonymous).Select(e => new[] { e.Name, string.Join(", ", e.Roles), string.Join(", ", e.Policies), e.AllowAnonymous ? "yes" : "" }));
        return md.ToString();
    }

