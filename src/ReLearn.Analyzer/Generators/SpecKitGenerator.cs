    private string DataModel(Capability cap)
    {
        var md = new Md().H(1, $"Data Model: {cap.Name}");
        md.P("Derived from ORM entities, mapping configuration, SQL in code, migrations and SQL scripts.");
        var ents = _v.Pack.Data.Entities.Where(e => cap.Entities.Contains(e.Name)).ToList();
        if (ents.Count > 0) md.Code("mermaid", Mermaid.Er(ents));
        foreach (var e in ents)
        {
            md.H(2, e.Name);
            md.P($"Table: `{(e.Schema != null ? e.Schema + "." : "")}{e.Table ?? e.Name}` · contexts: {string.Join(", ", e.DbContexts)} · source {_v.Evidence(e.Location)}");
            md.Table(new[] { "field", "type", "key", "nullable", "constraints / mapping" },
                e.Properties.Select(p => new[] { p.Name, p.Type, p.IsKey ? "PK" : "", p.Nullable ? "yes" : "", string.Join(", ", p.Constraints.Concat(p.Column != null ? new[] { "column " + p.Column } : Array.Empty<string>()).Concat(p.NavigationTo != null ? new[] { (p.IsCollection ? "1..* → " : "→ ") + p.NavigationTo } : Array.Empty<string>())) }));
            var cfg = _v.Pack.Data.ModelConfiguration.Where(c => c.Entity == e.Name).ToList();
            if (cfg.Count > 0) { md.L("Mapping configuration:").Nl(); foreach (var c in cfg) md.Bullet($"`{c.Text}`"); md.Nl(); }
            var erules = _v.Pack.Rules.Where(r => r.Entities.Contains(e.Name) && r.Kind is "declarative-validation" or "data-constraint" or "fluent-validation").ToList();
            if (erules.Count > 0) { md.L("Validation & constraints:").Nl(); foreach (var r in erules) md.Bullet($"{r.Id}: {Text.OneLine(r.Condition ?? r.Title, 200)}{(r.Message != null ? $" — \"{r.Message}\"" : "")}"); md.Nl(); }
        }
        var tables = cap.Entities.Where(n => ents.All(e => e.Name != n)).ToList();
        var objs = _v.Pack.Data.DbObjects.Where(o => tables.Contains(o.Name, StringComparer.OrdinalIgnoreCase) || o.ReferencedBy.Any(m => FlowsOf(cap).Any(f => f.Steps.Any(s => s.MethodId == m)))).ToList();
        if (objs.Count > 0)
        {
            md.H(2, "Database objects used directly");
            md.Table(new[] { "object", "kind", "source", "columns / dependencies" }, objs.Select(o => new[] { o.Name, o.Kind, o.Source, string.Join(", ", o.Columns.Take(12)) }));
        }
        var ops = _v.Pack.Data.Operations.Where(d => FlowsOf(cap).Any(f => f.Steps.Any(s => s.MethodId == d.MethodId))).ToList();
        if (ops.Count > 0)
        {
            md.H(2, "Data access in legacy flows");
            md.Table(new[] { "method", "operation", "targets", "technology", "sql", "source" },
                ops.Select(o => new[] { _v.MethodName(o.MethodId), o.Operation, string.Join(", ", o.Targets), o.Technology, o.Sql != null ? "`" + Text.OneLine(o.Sql, 160) + "`" + (o.DynamicSql ? " (dynamic)" : "") : "", _v.Evidence(o.Location) }));
        }
        return md.ToString();
    }

    private string Contracts(Capability cap)
    {
        var md = new Md().H(1, $"Legacy interface contracts: {cap.Name}");
        md.P("Contracts that existing users and systems depend on. Keep compatible or version explicitly (Constitution III). Generate formal OpenAPI/AsyncAPI files from these during `/speckit.plan`.");
        var eps = _v.Pack.EntryPoints.Where(e => cap.EntryPoints.Contains(e.Id)).ToList();
        var http = eps.Where(e => e.Route != null).ToList();
        if (http.Count > 0)
        {
            md.H(2, "Endpoints");
            md.Table(new[] { "id", "method", "route", "parameters", "returns", "auth", "source" },
                http.Select(e => new[] { e.Id, e.HttpMethod ?? "", e.Route ?? "", string.Join("; ", e.Parameters), e.ReturnType ?? "", e.AllowAnonymous ? "anonymous" : string.Join(", ", e.Roles.Concat(e.Policies).DefaultIfEmpty(e.RequiresAuth ? "authenticated" : "")), _v.Evidence(e.Location) }));
        }
        var ui = eps.Where(e => e.Screen != null && e.Route == null).ToList();
        var screens = _v.Pack.Journeys.Screens.Where(s => eps.Any(e => e.Screen == s.Id)).ToList();
        if (screens.Count > 0)
        {
            md.H(2, "Screens");
            foreach (var s in screens)
            {
                md.H(3, $"{s.Name} (`{s.Id}`, {s.Kind})");
                if (s.Fields.Count > 0) md.L("Fields: " + string.Join(", ", s.Fields.Select(f => $"`{f}`"))).Nl();
                if (s.Actions.Count > 0) md.L("Actions: " + string.Join(", ", s.Actions.Select(a => $"`{a}`"))).Nl();
            }
            if (ui.Count > 0)
                md.Table(new[] { "id", "screen", "trigger", "handler", "source" }, ui.Select(e => new[] { e.Id, e.Screen ?? "", e.Trigger ?? "", e.Name, _v.Evidence(e.Location) }));
        }
        var other = eps.Where(e => e.Route == null && e.Screen == null).ToList();
        if (other.Count > 0)
        {
            md.H(2, "Background / message entry points");
            md.Table(new[] { "id", "kind", "name", "trigger", "source" }, other.Select(e => new[] { e.Id, e.Kind, e.Name, e.Trigger ?? "", _v.Evidence(e.Location) }));
        }
        var ints = cap.Integrations.Where(_v.Integrations.ContainsKey).Select(i => _v.Integrations[i]).Where(i => i.Category != "config").ToList();
        if (ints.Count > 0)
        {
            md.H(2, "Outbound / inbound integrations");
            md.Table(new[] { "id", "category", "technology", "direction", "operation", "target", "api", "source" },
                ints.Select(i => new[] { i.Id, i.Category, i.Technology, i.Direction, i.Operation, i.Target ?? "", i.Api, _v.Evidence(i.Location) }));
        }
        return md.ToString();
    }

    private string Research(Capability cap)
    {
        var md = new Md().H(1, $"Research: {cap.Name} → {_v.Target.Name}");
        md.P("Pre-filled technology decisions for `/speckit.plan`, limited to the legacy constructs this capability actually uses. Confirm or override each decision.");
        foreach (var m in _v.MappingsFor(cap))
        {
            md.H(2, $"{m.Legacy} → {m.Target}");
            md.L($"**Decision**: {m.Target}  ").L($"**Rationale**: {m.Rationale ?? "Idiomatic equivalent on the target platform."}  ").L($"**Alternatives considered**: {m.Alternatives ?? "—"}").Nl();
            if (m.Notes != null) md.P($"_Notes_: {m.Notes}");
        }
        var facts = _v.Facts(cap).Where(f => f != "always" && _v.Target.Mappings.All(m => m.Match != f)).ToList();
        if (facts.Count > 0)
        {
            md.H(2, "Open decisions");
            foreach (var f in facts) md.Bullet($"`{f}` — [NEEDS CLARIFICATION: no predefined mapping in target profile]");
        }
        return md.ToString();
    }

    private string Checklist(Capability cap)
    {
        var md = new Md().H(1, $"Parity checklist: {cap.Name}");
        md.P("**Purpose**: verify behavioural parity with the legacy system before cut-over.  \n**Created**: " + _date);
        var n = 0;
        md.H(2, "Flows");
        foreach (var f in FlowsOf(cap)) md.L($"- [ ] CHK{++n:000} {f.Id} `{f.Name}` characterization tests pass on target");
        md.H(2, "Business rules");
        foreach (var r in RulesOf(cap).Where(r => !r.Trivial)) md.L($"- [ ] CHK{++n:000} {r.Id} ({r.Kind}) {Text.OneLine(r.Title, 120)}");
        md.H(2, "Data");
        foreach (var e in cap.Entities) md.L($"- [ ] CHK{++n:000} `{e}` migrated and reconciled (counts + checksums)");
        md.H(2, "Integrations");
        foreach (var i in cap.Integrations.Where(_v.Integrations.ContainsKey).Select(id => _v.Integrations[id]).Where(i => i.Category != "config"))
            md.L($"- [ ] CHK{++n:000} {i.Id} {i.Category}/{i.Technology} {i.Operation} {i.Target} verified end-to-end");
        md.H(2, "Security");
        md.L($"- [ ] CHK{++n:000} roles/policies mapped: {string.Join(", ", FlowsOf(cap).SelectMany(f => f.Roles).Distinct().DefaultIfEmpty("none found — confirm"))}");
        return md.ToString();
    }

    private string Evidence(Capability cap)
    {
        var md = new Md().H(1, $"Legacy evidence: {cap.Name} ({cap.Id})");
        md.P("Raw extraction for reviewers and implementers. Do not edit — regenerate with `relearn speckit`.");
        foreach (var f in FlowsOf(cap))
        {
            md.H(2, $"{f.Id}: {f.Name}");
            md.P($"Trigger: `{f.Trigger}` · layers: {string.Join(" → ", f.Layers)} · mutates: {(f.Mutates ? "yes" : "no")}{(f.Truncated ? " · **truncated**" : "")}");
            md.Code("mermaid", Mermaid.Sequence(f));
            md.Table(new[] { "#", "depth", "step", "stereotype", "data", "integrations", "rules" },
                f.Steps.Take(60).Select(s => new[] { s.Order.ToString(), s.Depth.ToString(), $"{s.Type}.{s.Method}", s.Stereotype, string.Join("; ", s.Data), string.Join("; ", s.Integrations), string.Join(", ", s.Rules) }));
        }
        md.H(2, "Rules (full detail)");
        foreach (var r in RulesOf(cap))
        {
            md.H(3, $"{r.Id} · {r.Kind} · {r.Confidence}");
            md.P(Text.OneLine(r.Title, 300));
            if (r.Condition != null) md.L($"- condition: `{Text.OneLine(r.Condition, 400)}`");
            if (r.Outcome != null) md.L($"- outcome: {Text.OneLine(r.Outcome, 300)}");
            if (r.Expression != null) md.L($"- expression: `{Text.OneLine(r.Expression, 400)}`");
            if (r.Message != null) md.L($"- message: \"{r.Message}\"");
            if (r.Table != null) foreach (var row in r.Table) md.L($"  - `{row[0]}` → `{row[1]}`");
            md.L($"- source: {_v.Evidence(r.Location)}{(r.MethodId != null ? " in `" + _v.MethodName(r.MethodId) + "`" : "")}").Nl();
        }
        return md.ToString();
    }
