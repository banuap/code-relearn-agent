    private List<BusinessFlow> FlowsOf(Capability c) => c.Flows.Where(_v.Flows.ContainsKey).Select(id => _v.Flows[id]).ToList();
    private List<BusinessRule> RulesOf(Capability c) => c.Rules.Where(_v.Rules.ContainsKey).Select(id => _v.Rules[id]).ToList();

    private string Spec(Capability cap, string folder)
    {
        var flows = FlowsOf(cap);
        var rules = RulesOf(cap);
        var md = new Md();
        md.L($"# Feature Specification: {cap.Name}").Nl();
        md.L($"**Feature Branch**: `{folder}`  ").L($"**Created**: {_date}  ").L("**Status**: Draft  ")
          .L($"**Input**: User description: \"Re-implement the legacy '{cap.Name}' capability ({cap.Id}) on {_v.Target.Name}, preserving the behaviour captured by ReLearn.\"").Nl();
        if (cap.Description != null) md.P(cap.Description);
        md.P("> Generated from static analysis. Statements in `code` are legacy conditions — `/speckit.clarify` should restate them in business language with a domain expert. Items marked [NEEDS CLARIFICATION] could not be determined from code alone.");

        md.H(2, "User Scenarios & Testing *(mandatory)*");
        var storyNo = 0;
        var orderedFlows = flows.OrderByDescending(f => f.Mutates).ThenByDescending(f => f.Rules.Count).ThenBy(f => f.Name).ToList();
        foreach (var f in orderedFlows)
        {
            storyNo++;
            var ep = _v.EntryPoints.GetValueOrDefault(f.EntryPointId);
            var prio = storyNo <= 2 && f.Mutates ? "P1" : f.Mutates || f.Rules.Count > 0 ? "P2" : "P3";
            md.H(3, $"User Story {storyNo} - {HumanFlow(f)} (Priority: {prio})");
            md.P($"As a **{PackView.Actor(f)}**, I want to {HumanFlow(f).ToLowerInvariant()} so that {f.Goal ?? $"[NEEDS CLARIFICATION: business outcome of `{f.Name}`]"}.");
            md.P($"**Why this priority**: {(f.Mutates ? "changes system state" : "read-only")}; {f.Rules.Count} business rule(s); touches {string.Join(", ", f.EntityOperations.Select(kv => $"{kv.Key} ({string.Join("/", kv.Value)})").DefaultIfEmpty("no persistent data"))}.");
            md.P($"**Independent Test**: replay the recorded legacy characterization cases for `{f.Id}` ({ep?.Kind} `{f.Trigger}`) against the new implementation and compare outputs and persisted state.");
            md.L("**Acceptance Scenarios**:").Nl();
            var n = 0;
            var frules = f.Rules.Where(_v.Rules.ContainsKey).Select(id => _v.Rules[id]).ToList();
            if (frules.Count == 0)
                md.L($"{++n}. **Given** valid input, **When** the {PackView.Actor(f)} performs \"{HumanFlow(f)}\", **Then** the result matches the legacy system's response and persisted state.");
            foreach (var r in frules.Take(12)) md.L($"{++n}. {Scenario(r, f)}");
            if (frules.Count > 12) md.L($"{++n}. …and {frules.Count - 12} further rules listed under Functional Requirements.");
            md.Nl();
        }
        if (flows.Count == 0) md.P("[NEEDS CLARIFICATION: no entry point found for this capability]");

        md.H(3, "Edge Cases");
        foreach (var r in rules.Where(r => r.Kind is "existence" or "guard").Take(15))
            md.Bullet($"What happens when `{Text.OneLine(r.Condition, 140)}`? Legacy: {r.Outcome}{(r.Message != null ? $" (\"{r.Message}\")" : "")} — {r.Id}");
        foreach (var f in flows.Where(f => f.Truncated)) md.Bullet($"{f.Id} call depth exceeded the analysis limit — deeper behaviour must be reviewed manually.");
        var dyn = _v.Pack.Data.Operations.Where(d => d.DynamicSql && flows.Any(f => f.Steps.Any(s => s.MethodId == d.MethodId))).ToList();
        if (dyn.Count > 0) md.Bullet($"{dyn.Count} dynamic SQL site(s) — filtering/sorting behaviour must be reproduced (see legacy-evidence.md).");
        md.Bullet("Concurrent modification of the same record — [NEEDS CLARIFICATION: legacy locking/concurrency semantics]");
        md.Nl();

        md.H(2, "Requirements *(mandatory)*");
        md.H(3, "Functional Requirements");
        var fr = 0;
        var trace = new List<string[]>();
        foreach (var f in orderedFlows)
        {
            var id = $"FR-{++fr:000}";
            md.Bullet($"**{id}**: System MUST allow {PackView.Actor(f)} to {HumanFlow(f).ToLowerInvariant()}{(f.Roles.Count > 0 ? $", restricted to {string.Join(", ", f.Roles)}" : "")}. *(legacy {f.Id})*");
            trace.Add(new[] { id, f.Id, f.Name, _v.Evidence(_v.EntryPoints.GetValueOrDefault(f.EntryPointId)?.Location) });
        }
        foreach (var r in rules.Where(r => !r.Trivial).OrderBy(r => r.Kind).ThenBy(r => r.Id))
        {
            var id = $"FR-{++fr:000}";
            md.Bullet($"**{id}**: {Requirement(r)} *(legacy {r.Id}{(r.Confidence == "low" ? ", low confidence — [NEEDS CLARIFICATION]" : "")})*");
            trace.Add(new[] { id, r.Id, Text.OneLine(r.Title, 80), _v.Evidence(r.Location) });
        }
        var intIds = cap.Integrations.Where(_v.Integrations.ContainsKey).Select(i => _v.Integrations[i]).Where(i => i.Category is not ("config" or "file") ).ToList();
        foreach (var g in intIds.GroupBy(i => (i.Category, i.Operation, i.Target)))
        {
            var i = g.First();
            var id = $"FR-{++fr:000}";
            md.Bullet($"**{id}**: System MUST {IntegrationVerb(i)} *(legacy {string.Join(", ", g.Select(x => x.Id))}: {i.Technology})*");
            trace.Add(new[] { id, string.Join(", ", g.Select(x => x.Id)), $"{i.Category}/{i.Technology}", _v.Evidence(i.Location) });
        }
        md.Nl();

        md.H(3, "Key Entities");
        foreach (var e in _v.Pack.Data.Entities.Where(e => cap.Entities.Contains(e.Name)))
        {
            var keys = e.Properties.Where(p => p.IsKey).Select(p => p.Name);
            var rels = e.Properties.Where(p => p.NavigationTo != null).Select(p => $"{(p.IsCollection ? "has many" : "belongs to")} {p.NavigationTo}");
            md.Bullet($"**{e.Name}**: {e.Properties.Count(p => p.NavigationTo == null)} attributes (key: {string.Join(", ", keys.DefaultIfEmpty("?"))}){(rels.Any() ? "; " + string.Join("; ", rels) : "")}. See data-model.md.");
        }
        foreach (var t in cap.Entities.Where(n => _v.Pack.Data.Entities.All(e => e.Name != n)))
            md.Bullet($"**{t}**: database object accessed directly (no ORM entity). See data-model.md.");
        md.Nl();

        md.H(2, "Success Criteria *(mandatory)*");
        md.H(3, "Measurable Outcomes");
        md.Bullet($"**SC-001**: 100% of the {rules.Count(r => !r.Trivial)} legacy business rules in this spec have passing parity tests.");
        md.Bullet($"**SC-002**: All {flows.Count} legacy operations are available to the same actors with equivalent inputs, outputs and side effects (contract tests green).");
        if (cap.Entities.Count > 0) md.Bullet($"**SC-003**: Data for {string.Join(", ", cap.Entities.Take(6))} reconciles after migration (row counts and checksums match the legacy store).");
        md.Bullet("**SC-004**: User-facing response times are no worse than the legacy baseline [NEEDS CLARIFICATION: legacy p95 baseline].");
        md.Nl();

        md.H(2, "Assumptions");
        md.Bullet("Behaviour is derived from source code; runtime configuration, data-driven rules and stored-procedure logic not visible in code must be confirmed with domain experts.");
        md.Bullet($"Target platform and technology choices are governed by the constitution and `.specify/relearn/target-profile.md` ({_v.Target.Name}).");
        md.Nl();

        md.H(2, "Legacy Traceability (ReLearn)");
        md.Table(new[] { "requirement", "legacy id", "description", "source" }, trace);
        return md.ToString();
    }

    private string HumanFlow(BusinessFlow f)
    {
        if (!string.IsNullOrWhiteSpace(f.BusinessName)) return f.BusinessName!;
        var ep = _v.EntryPoints.GetValueOrDefault(f.EntryPointId);
        var method = ep != null && _v.Methods.TryGetValue(ep.MethodId, out var m) ? m.Name : f.Name;
        method = Regex.Replace(method, "(Async|_Click|_Load|Click|OnPost|OnGet|Handler)$", "").Replace("btn", "").Replace("_", " ");
        if (method.StartsWith("On") && method.Length > 2 && char.IsUpper(method[2])) method = method[2..];
        var words = Text.Humanize(method);
        var entity = f.EntityOperations.Keys.FirstOrDefault();
        if (Regex.IsMatch(words, "^(Index|Get|List|Details?|Load)$", RegexOptions.IgnoreCase) && entity != null) words = $"View {entity}";
        return words.Length > 0 ? char.ToUpperInvariant(words[0]) + words[1..] : f.Name;
    }

    private string Scenario(BusinessRule r, BusinessFlow f)
    {
        var act = $"**When** the {PackView.Actor(f)} performs \"{HumanFlow(f)}\"";
        if (!string.IsNullOrWhiteSpace(r.BusinessStatement))
            return $"**Given** the situation described by {r.Id}, {act}, **Then** {char.ToLowerInvariant(r.BusinessStatement![0]) + r.BusinessStatement[1..].TrimEnd('.')}. ({r.Id})";
        var cond = string.IsNullOrEmpty(r.Condition) ? null : $"`{Text.OneLine(r.Condition, 160)}`";
        return r.Kind switch
        {
            "validation" or "declarative-validation" or "fluent-validation" =>
                $"**Given** {cond ?? "invalid input"}, {act}, **Then** the request is rejected{(r.Message != null ? $" with message \"{r.Message}\"" : "")}. ({r.Id})",
            "existence" => $"**Given** {cond ?? "the referenced record does not exist"}, {act}, **Then** the system reports that the item was not found. ({r.Id})",
            "authorization" => $"**Given** the user does not satisfy {cond ?? "the required role/policy"}, {act}, **Then** access is denied. ({r.Id})",
            "calculation" => $"**Given** {(cond != null ? cond : "the relevant inputs")}, {act}, **Then** `{Text.OneLine(r.Expression, 160)}` is computed identically to legacy (incl. rounding). ({r.Id})",
            "state-transition" => $"**Given** {cond ?? "the operation succeeds"}, {act}, **Then** `{Text.OneLine(r.Outcome, 120)}`. ({r.Id})",
            "decision-table" => $"**Given** each case of `{Text.OneLine(r.Condition, 80)}`, {act}, **Then** the outcome follows the legacy decision table ({r.Table?.Count ?? 0} rows, see FR). ({r.Id})",
            "parameter" => $"**Given** business parameter `{r.Expression}`, {act}, **Then** the same value governs the behaviour [NEEDS CLARIFICATION: make configurable?]. ({r.Id})",
            _ => $"**Given** {cond ?? "the stated condition"}, {act}, **Then** {Text.OneLine(r.Outcome ?? r.Title, 160)}. ({r.Id})",
        };
    }

    private static string Requirement(BusinessRule r)
    {
        if (!string.IsNullOrWhiteSpace(r.BusinessStatement))
            return (r.BusinessStatement!.StartsWith("System ") ? r.BusinessStatement : "System MUST " + char.ToLowerInvariant(r.BusinessStatement[0]) + r.BusinessStatement[1..]).TrimEnd('.') + "."
                   + (r.Condition != null ? $" (legacy condition `{Text.OneLine(r.Condition, 120)}`)" : "");
        var cond = Text.OneLine(r.Condition, 200);
        var msg = r.Message != null ? $" with message \"{r.Message}\"" : "";
        return r.Kind switch
        {
            "validation" => $"System MUST reject the operation when `{cond}`{msg}.",
            "guard" => $"System MUST reject the operation when `{cond}`.",
            "existence" => $"System MUST report not-found when `{cond}`.",
            "authorization" => $"System MUST enforce authorization `{cond}`.",
            "declarative-validation" or "fluent-validation" => $"System MUST validate `{cond}`{msg}.",
            "decision" => $"System MUST, when `{cond}`, {Text.OneLine(r.Outcome, 200)}.",
            "decision-table" => "System MUST apply the decision table on `" + cond + "`: " + string.Join("; ", (r.Table ?? new()).Select(row => $"{row[0]} → {row[1]}")),
            "state-transition" => $"System MUST perform state change `{Text.OneLine(r.Outcome, 160)}`{(cond.Length > 0 ? $" when `{cond}`" : "")}.",
            "calculation" => $"System MUST compute `{Text.OneLine(r.Expression, 220)}`{(cond.Length > 0 ? $" when `{cond}`" : "")}, preserving numeric precision and rounding.",
            "parameter" => $"System MUST use business parameter `{r.Expression}` (externalize as configuration).",
            "data-constraint" => $"System MUST enforce data constraint `{Text.OneLine(r.Condition, 200)}`.",
            _ => $"System MUST honour: {Text.OneLine(r.Title, 200)}.",
        };
    }

    private static string IntegrationVerb(IntegrationPoint i)
    {
        var target = i.Target != null ? $" `{i.Target}`" : "";
        return i.Category switch
        {
            "stream" or "queue" or "pubsub" when i.Direction == "outbound" => $"publish/send messages to{target} when the triggering flow completes",
            "stream" or "queue" or "pubsub" when i.Direction == "inbound" => $"consume messages from{target} and process them idempotently",
            "cache" => $"cache{target} with equivalent keys, expiry and invalidation semantics",
            "http" or "soap" or "grpc" => $"call the external service{target} with equivalent request/response semantics and error handling",
            "email" or "notification" => "send the same notifications to the same recipients",
            "scheduler" => $"run the scheduled/background work{target} on an equivalent schedule",
            "storage" => $"read/write files/objects{target} in durable storage",
            "realtime" => "push real-time updates to connected clients",
            "identity" => "authenticate and manage users with equivalent identity semantics",
            "platform" => $"replace platform-specific dependency ({i.Technology}) with a portable equivalent",
            "mediator" => "dispatch the in-process command/event to its handler",
            _ => $"preserve {i.Category} integration ({i.Operation}){target}",
        };
    }

